def build_province_raw() -> pd.DataFrame:
    """由 2019 锚点 + 年度景气指数 + 确定性扰动，生成省级面板原始数据（含脏数据）。"""
    rng = np.random.default_rng(RANDOM_SEED)
    rows = []
    for province, region, rev0, tou0, gdp0, pop0 in PROVINCE_ANCHOR_2019:
        # 每个省份一套独立但可复现的扰动系数
        noise_rev = rng.normal(1.0, 0.035, len(YEARS))
        noise_tou = rng.normal(1.0, 0.030, len(YEARS))
        noise_gdp = rng.normal(1.0, 0.020, len(YEARS))
        for i, year in enumerate(YEARS):
            # 优先使用特殊修正指数，否则使用全国景气指数
            f_rev, f_tou = SPECIAL.get((province, year), (REV_INDEX[year], TOU_INDEX[year]))
            rev = rev0 * f_rev * noise_rev[i]
            tou = tou0 * f_tou * noise_tou[i]
            gdp = gdp0 * GDP_INDEX[year] * noise_gdp[i]
            pop = pop0 * POP_INDEX[year]
            rows.append({
                "省份": province,
                "所属区域": region,
                "年份": year,
                "省份旅游收入_亿元": round(rev, 1),
                "接待游客数量_万人次": round(tou, 1),
                "省份GDP_亿元": round(gdp, 1),
                "常住人口_万人": round(pop, 1),
            })
    df = pd.DataFrame(rows)

    # ---- 人为注入"脏数据"，供预处理模块清洗（模拟真实采集过程）------------
    # (a) 缺失值：数值缺失 4 处 + 分类字段缺失 1 处
    df.loc[(df["省份"] == "西藏") & (df["年份"] == 2016), "省份旅游收入_亿元"] = np.nan
    df.loc[(df["省份"] == "青海") & (df["年份"] == 2018), "接待游客数量_万人次"] = np.nan
    df.loc[(df["省份"] == "宁夏") & (df["年份"] == 2021), "省份GDP_亿元"] = np.nan
    df.loc[(df["省份"] == "甘肃") & (df["年份"] == 2017), "常住人口_万人"] = np.nan
    df.loc[(df["省份"] == "内蒙古") & (df["年份"] == 2020), "所属区域"] = None

    # (b) 异常值：量级错误、符号错误、哨兵值（999999）
    df.loc[(df["省份"] == "云南") & (df["年份"] == 2018), "省份旅游收入_亿元"] = 98500.0   # 量级异常
    df.loc[(df["省份"] == "青海") & (df["年份"] == 2016), "省份旅游收入_亿元"] = -120.0     # 负值异常
    df.loc[(df["省份"] == "西藏") & (df["年份"] == 2017), "接待游客数量_万人次"] = 999999.0  # 哨兵值
    df.loc[(df["省份"] == "海南") & (df["年份"] == 2023), "常住人口_万人"] = 99999.9        # 哨兵值
    return df


