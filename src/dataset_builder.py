def build_all_raw() -> dict:
    """返回 4 张原始表的 DataFrame 字典。"""
    return {
        "national_annual.csv": pd.DataFrame({
            "年份": NATIONAL_RAW["年份"],
            "全国旅游总收入_亿元": NATIONAL_RAW["全国旅游总收入_亿元"],
            "国内游客总人次_亿人次": NATIONAL_RAW["国内游客总人次_亿人次"],
            "全国GDP_亿元": NATIONAL_RAW["全国GDP_亿元"],
            # 该列刻意留空，由预处理模块按"旅游总收入 / GDP × 100"派生并校验
            "旅游收入占GDP比重_%": [None] * len(NATIONAL_RAW["年份"]),
        }),
        "province_tourism.csv": build_province_raw(),
        "holiday_tourism.csv": build_holiday_raw(),
        "city_tourism.csv": build_city_raw(),
    }


def build_raw_csv(data_dir: str = DATA_DIR, force: bool = False, verbose: bool = True) -> None:
    """把内置数据写成 csv（utf-8-sig，方便 Excel 直接打开中文）。

    :param data_dir: 输出目录
    :param force:    True 则覆盖已存在的文件；False 表示文件存在时跳过
    """
    os.makedirs(data_dir, exist_ok=True)
    tables = build_all_raw()
    for filename, df in tables.items():
        path = os.path.join(data_dir, filename)
        if os.path.exists(path) and not force:
            if verbose:
                print(f"[跳过] {filename} 已存在（如需重建请设置 force=True）")
            continue
        df.to_csv(path, index=False, encoding="utf-8-sig")
        if verbose:
            print(f"[生成] {filename:<26} 行数={len(df):>4}  列数={df.shape[1]}")
    if verbose:
        print(f"\n原始数据集已写入：{data_dir}")


if __name__ == "__main__":
    build_raw_csv(force=True)
