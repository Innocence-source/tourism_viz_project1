def build_city_raw() -> pd.DataFrame:
    """由城市锚点 + 年度指数生成城市面板数据，并注入缺失/异常。"""
    rng = np.random.default_rng(RANDOM_SEED + 1)
    rows = []
    for city, province, rev0, tou0 in CITY_ANCHOR_2019:
        noise_rev = rng.normal(1.0, 0.045, len(YEARS))
        noise_tou = rng.normal(1.0, 0.040, len(YEARS))
        for i, year in enumerate(YEARS):
            f_rev, f_tou = SPECIAL.get((province, year), (REV_INDEX[year], TOU_INDEX[year]))
            rows.append({
                "热门旅游城市": city,
                "所属省份": province,
                "年份": year,
                "城市旅游收入_亿元": round(rev0 * f_rev * noise_rev[i], 1),
                "接待游客量_万人次": round(tou0 * f_tou * noise_tou[i], 1),
            })
    df = pd.DataFrame(rows)
    # 注入 2 处缺失 + 1 处异常
    df.loc[(df["热门旅游城市"] == "三亚") & (df["年份"] == 2016), "接待游客量_万人次"] = np.nan
    df.loc[(df["热门旅游城市"] == "洛阳") & (df["年份"] == 2020), "城市旅游收入_亿元"] = np.nan
    df.loc[(df["热门旅游城市"] == "厦门") & (df["年份"] == 2019), "城市旅游收入_亿元"] = 71200.0  # 量级异常
    return df


